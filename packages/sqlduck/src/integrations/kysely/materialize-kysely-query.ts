import type { DuckdbDatasource } from "@flowblade/source-duckdb";
import { withConnectionLock } from "@flowblade/source-duckdb";

import { DuckTableLoader } from "../../loader/duck-table-loader.ts";
import { ChunkAppenderStrategy } from "../../loader/strategies/chunk-appender/chunk-appender-strategy.ts";
import type { LoadResult } from "../../loader/types.ts";
import type { Table } from "../../objects/table.ts";
import { createRandomTable } from "../../table/create-random-table.ts";
import { isDuckdbValidIdentifier } from "../../validation/core/is-duckdb-valid-identifier.ts";
import type { TableSchemaZod } from "../../validation/zod/table-schema-zod.ts";
import type { KyselyQueryWithZodSchema } from "./kysely-query-with-zod-schema.ts";

const chunkSize = 1024;

export type MaterializeKyselyQueryParams = {
  dsDuck: DuckdbDatasource;
  table: KyselyQueryWithZodSchema;
  /**
   * Database where the temporary table is created (e.g. an attached file database).
   * Defaults to the connection's current database.
   */
  database?: string | undefined;
  /**
   * Schema where the temporary table is created (must already exist).
   * Defaults to the connection's current schema.
   */
  schema?: string | undefined;
  /** Stops the Kysely query stream and the load. */
  signal?: AbortSignal | undefined;
};

/**
 * Return the invalid `database` / `schema` name message, if any. The names
 * are interpolated as-is in the DDL and in the final DROP statement.
 */
export const getInvalidMaterializationTarget = (params: {
  database?: string | undefined;
  schema?: string | undefined;
}): string | null => {
  for (const [kind, name] of [
    ["database", params.database],
    ["schema", params.schema],
  ] as const) {
    if (name !== undefined && !isDuckdbValidIdentifier(name)) {
      return `Invalid ${kind} name '${name}'`;
    }
  }
  return null;
};

/**
 * Create the (not yet existing) randomly named table a kysely query is
 * materialized into.
 */
export const createMaterializedTable = (params: {
  database?: string | undefined;
  schema?: string | undefined;
}): Table => {
  const { database, schema } = params;
  return createRandomTable({
    prefix: "_materialized",
    ...(database === undefined ? {} : { database }),
    ...(schema === undefined ? {} : { schema }),
  });
};

/**
 * Stream the rows of a kysely query into a duckdb table. Throws when the
 * load fails: the table may then be partially created and must be dropped.
 */
export const loadKyselyQueryIntoTable = async (
  params: MaterializeKyselyQueryParams & { materializedTable: Table }
): Promise<LoadResult> => {
  const { dsDuck, table, materializedTable, signal } = params;
  return await new DuckTableLoader({
    conn: dsDuck.getConnection(),
    strategy: new ChunkAppenderStrategy({
      chunkSize,
      flushEveryRows: 100 * chunkSize,
    }),
  }).load({
    table: materializedTable,
    // Typed after the kysely query, unsupported zod types are rejected
    // when the table is created
    schema: table.getSchema() as TableSchemaZod,
    rows: table.getQuery().stream({ chunkSize, signal }),
    mode: "create",
    checkpoint: {
      onComplete: materializedTable.databaseName !== undefined,
    },
    signal,
  });
};

/**
 * Best effort drop: a failure must not hide the query result (or its error).
 */
export const dropTableQuietly = async (
  dsDuck: DuckdbDatasource,
  table: Table
): Promise<void> => {
  try {
    // the name is generated by createRandomTable (validated identifier)
    const conn = dsDuck.getConnection();
    await withConnectionLock(conn, () =>
      conn.run(`DROP TABLE IF EXISTS ${table.getFullName()}`)
    );
  } catch {
    // ignore
  }
};

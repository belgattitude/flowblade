/**
 * Generate `src/manager/settings/duck-settings.generated.ts` from the
 * settings of the installed DuckDB version.
 *
 * `duckdb_settings().scope` can't tell which settings accept `SET SESSION`
 * (it reports GLOBAL for most of them), so each setting is probed with
 * `SET SESSION <name> = <current value>` on a throwaway in-memory instance.
 *
 * Run it after upgrading `@duckdb/node-api`:
 *
 * ```bash
 * pnpm generate-settings-types && pnpm lint-fix
 * ```
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";

import { DuckDBInstance } from "@duckdb/node-api";

const outputFile = path.resolve(
  import.meta.dirname,
  "../src/manager/settings/duck-settings.generated.ts"
);

/**
 * Internal settings, left out of the types.
 */
const isExcluded = (name: string) => name.startsWith("debug_");

/**
 * Errors meaning the setting can't be set for a session only.
 */
const globalOnlyErrors = [
  /cannot be set locally/i,
  /cannot be set as a session variable/i,
];

const tsTypeByInputType: Record<string, string> = {
  BOOLEAN: "boolean",
  BIGINT: "number",
  UBIGINT: "number",
  DOUBLE: "number",
  VARCHAR: "string",
  "VARCHAR[]": "readonly string[]",
  "MAP(VARCHAR, VARCHAR)": "Readonly<Record<string, string>>",
};

type SettingRow = {
  name: string;
  value: string;
  description: string;
  input_type: string;
};

const toJsDoc = (row: SettingRow, aliasOf: string | undefined) => {
  const lines = [row.description.replaceAll("*/", "*\\/")];
  if (aliasOf !== undefined) {
    lines.push(`Alias of \`${aliasOf}\`.`);
  }
  lines.push(`DuckDB type: \`${row.input_type}\``);
  return `  /**\n${lines.map((l) => `   * ${l}`).join("\n   *\n")}\n   */`;
};

const main = async () => {
  const instance = await DuckDBInstance.create(":memory:");
  const conn = await instance.connect();
  const versionReader = await conn.runAndReadAll("SELECT version() AS version");
  const [version] = versionReader.getRowObjects();

  const settingsReader = await conn.runAndReadAll(
    "SELECT name, value, description, input_type FROM duckdb_settings() ORDER BY name"
  );
  const rows = settingsReader.getRowObjectsJson() as SettingRow[];

  // alias -> canonical name
  const aliasReader = await conn.runAndReadAll(
    "SELECT name, unnest(aliases) AS alias FROM duckdb_settings()"
  );
  const aliasRows = aliasReader.getRowObjectsJson() as {
    name: string;
    alias: string;
  }[];
  const aliasOf = new Map(aliasRows.map((r) => [r.alias, r.name]));

  const session: string[] = [];
  const global: string[] = [];
  for (const row of rows) {
    if (isExcluded(row.name)) {
      continue;
    }
    const tsType = tsTypeByInputType[row.input_type];
    if (tsType === undefined) {
      throw new Error(
        `Unsupported input_type '${row.input_type}' for setting '${row.name}'`
      );
    }
    const name = `"${row.name.replaceAll('"', '""')}"`;
    let isGlobalOnly = false;
    try {
      await conn.run(
        `SET SESSION ${name} = '${(row.value ?? "").replaceAll("'", "''")}'`
      );
      await conn.run(`RESET SESSION ${name}`);
    } catch (error) {
      // Other errors are about the probed value (ie: an extension not
      // installed), the setting itself accepts SET SESSION.
      isGlobalOnly = globalOnlyErrors.some((re) =>
        re.test(error instanceof Error ? error.message : String(error))
      );
    }
    const entry = `${toJsDoc(row, aliasOf.get(row.name))}\n  ${JSON.stringify(row.name)}?: ${tsType};`;
    (isGlobalOnly ? global : session).push(entry);
  }
  conn.closeSync();
  instance.closeSync();

  const content = `// Generated by scripts/generate-duck-settings-types.ts from DuckDB ${String(version?.version)}, do not edit.

/**
 * DuckDB settings that can be set for a single connection (\`SET SESSION\`),
 * without affecting the other connections of the instance.
 */
export type DuckSessionSettings = {
${session.join("\n")}
};

/**
 * DuckDB settings that can only be set for the whole instance
 * (\`SET GLOBAL\`): they apply to every connection and attached database.
 * Prefer setting them when creating the instance.
 */
export type DuckGlobalSettings = {
${global.join("\n")}
};
`;
  await writeFile(outputFile, content);
  console.log(
    `${outputFile}: ${session.length} session settings, ${global.length} global settings (DuckDB ${String(version?.version)})`
  );
};

await main();
